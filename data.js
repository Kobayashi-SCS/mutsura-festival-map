/* =====================================================================
   文化祭フロアマップ データファイル
   ---------------------------------------------------------------------
   ここを書き換えるだけで、マップの内容が変わります。
   ※ 今は「仮のサンプル」が入っています。実際の内容に差し替えてください。

   【書き方】
   R("ラベル", "出し物名", "説明", "写真のパス")   … 教室
   B("ラベル", "出し物名", "説明", "写真のパス")   … 中庭などの出店
   T()  … トイレ     S()  … 階段     E("昇降口") … 出入口
   K("休憩所", "説明") … 休憩所

   ・説明と写真は省略できます。  例: R("中1-A", "お化け屋敷")
   ・写真は photos フォルダに入れ、"photos/ファイル名.jpg" と書きます。
   ・各階の並び順(簡易版の階): 前半の半分が廊下の片側、後半が反対側に表示されます。
   ・実際の平面図どおりに描く階は、下の RM / WF などの「座標で書く」方式です。
   ・文字に " を使う場合は \" と書くか、「 」を使ってください。
   ===================================================================== */

const R = (label, booth, desc = "", photo = "") => ({ type: "room", label, booth, desc, photo });
const B = (label, booth, desc = "", photo = "") => ({ type: "booth", label, booth, desc, photo });
const G = (label, booth, desc = "", photo = "") => ({ type: "stage", label, booth, desc, photo });
const T = (label = "トイレ") => ({ type: "toilet", label });
const S = (label = "階段") => ({ type: "stairs", label });
const E = (label = "出入口") => ({ type: "entrance", label });
const K = (label = "休憩所", desc = "") => ({ type: "rest", label, desc });

/* ---- 平面図(部屋の形どおりに描くフロア)用 ----
   座標は x, y, 幅 w, 高さ h (フロア図は 横1000 × 縦560 の座標)。
   RM(x, y, w, h, "教室名", { tone: "g", booth: "出し物名", desc: "説明", photo: "photos/a.jpg", yen: true })
        tone: "g"=緑 / "p"=ピンク     yen: true で ¥マーク(斜線)を表示
   CL 使用しない部屋 / WF 女子トイレ / WM 男子トイレ / WX 男女トイレ / ST 階段 / EV エレベーター
   SH 下駄箱 / VM 自販機 / SV サービス(保健室など) / RS 休憩所 / PG(type, "x,y x,y ...", 名前) 多角形の部屋
   TX 文字 / AR 矢印 / FL 床の色 */
const RM = (x, y, w, h, label, o = {}) => ({ type: "room", x, y, w, h, label, booth: "", desc: "", photo: "", ...o });
const CL = (x, y, w, h, label = "", o = {}) => ({ type: "closed", x, y, w, h, label, ...o });
const WF = (x, y, w, h) => ({ type: "toilet", sex: "f", x, y, w, h, label: "女子トイレ" });
const WM = (x, y, w, h) => ({ type: "toilet", sex: "m", x, y, w, h, label: "男子トイレ" });
const WX = (x, y, w, h) => ({ type: "toilet", sex: "mf", x, y, w, h, label: "トイレ" });
const ST = (x, y, w, h, dir = "v", o = {}) => ({ type: "stairs", x, y, w, h, dir, label: "階段", ...o });
const EV = (x, y, w, h) => ({ type: "elevator", x, y, w, h, label: "エレベーター" });
const SH = (x, y, w, h, o = {}) => ({ type: "shoebox", x, y, w, h, label: "下駄箱", ...o });
const VM = (x, y, w, h) => ({ type: "vending", x, y, w, h, label: "自販機" });
const SV = (x, y, w, h, label, o = {}) => ({ type: "service", x, y, w, h, label, booth: "", desc: "", photo: "", ...o });
const RS = (x, y, w, h, label, o = {}) => ({ type: "rest", x, y, w, h, label, booth: "", desc: "", photo: "", ...o });
const PG = (type, pts, label = "", o = {}) => ({ type, pts, label, booth: "", desc: "", photo: "", ...o });
const TX = (x, y, text, fs = 30, o = {}) => ({ t: "text", x, y, text, fs, ...o });
const AR = (x, y, dir) => ({ t: "arrow", x, y, dir });
const FL = (x, y, w, h, fill = "#f2f2f2") => ({ t: "rect", x, y, w, h, fill, under: true });

